function openQuiz(quizData, quizTitle = 'Թեստ') {
  const quizArea = document.getElementById('quizArea');
  if (!quizArea || !quizData) return;

  const startButton = document.getElementById('openQuiz');
  if (startButton) {
    startButton.style.display = 'none';
  }
  
  quizArea.innerHTML = '';
  quizArea.classList.remove('visible');
  
  const cardTitle = document.querySelector('.quiz-card h3');
  const cardSub = document.querySelector('.quiz-card p');

  if (cardTitle) {
      cardTitle.textContent = quizTitle;
  }
  if (cardSub) {
      cardSub.textContent = 'Ընտրեք ճիշտ պատասխանները և սեղմեք "Ավարտել թեստը"։';
  }

  const closeBtn = document.createElement('button');
  closeBtn.textContent = '✖';
  closeBtn.className = 'closeQuiz';
  
  closeBtn.onclick = () => {
    if (cardTitle) cardTitle.textContent = 'Թեստ';
    if (cardSub) cardSub.textContent = 'Փորձնական թեստ՝ թեմաների հիման վրա։';
    
    quizArea.classList.remove('visible');
    
    setTimeout(() => {
      quizArea.innerHTML = '';
      if (startButton) startButton.style.display = 'flex';
    }, 500); 
  };
  
  const quizCard = document.getElementById('quiz');
  if (quizCard) {
      const existingClose = quizCard.querySelector('.closeQuiz');
      if (existingClose) existingClose.remove();
      
      quizCard.appendChild(closeBtn);
  }

  const form = document.createElement('form');
  quizData.forEach((item, i) => { 
    const qdiv = document.createElement('div');
    qdiv.className = 'question';
    qdiv.innerHTML = `<strong>${i + 1}. ${item.q}</strong>`;
    item.opts.forEach((opt, j) => {
      qdiv.innerHTML += `<div><label><input type="radio" name="q${i}" value="${j}"> ${opt}</label></div>`;
    });
    form.appendChild(qdiv);
  });

  const btn = document.createElement('button');
  btn.textContent = 'Ավարտել թեստը';
  btn.className = 'btn';
  btn.type = 'button';
  btn.onclick = () => gradeQuiz(form, quizData);
  form.appendChild(btn);
  quizArea.appendChild(form);

  setTimeout(() => {
    quizArea.classList.add('visible');
    quizArea.scrollIntoView({ behavior: 'smooth' });
  }, 10);
}

function gradeQuiz(form, quizData) {
  let score = 0;
  quizData.forEach((q, i) => {
    const selected = form[`q${i}`];
    const checked = [...selected].find(x => x.checked);
    if (checked && +checked.value === q.a) score++;
  });
  const pct = Math.round((score / quizData.length) * 100);
  alert(`Ճիշտ պատասխաններ՝ ${score}/${quizData.length} (${pct}%)`);
}

